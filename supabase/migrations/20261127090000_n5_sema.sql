create function public.n5_admin_verisi()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'questions', coalesce((
      select jsonb_agg(public.n5_soru_json(q) order by q.sira)
      from public.n5_questions q where q.silindi is null
    ), '[]'::jsonb),
    'settings', (select public.n5_ayarlar_json(s) from public.n5_settings s where s.id),
    'stats', (
      select jsonb_build_object(
        'games', t.games,
        'finished', t.finished,
        'totalCorrect', t.total_correct,
        'perQuestion', coalesce((
          select jsonb_object_agg(qs.question_id, jsonb_build_object('asked', qs.asked, 'correct', qs.correct))
          from public.n5_question_stats qs
        ), '{}'::jsonb)
      )
      from public.n5_stats_totals t where t.id
    )
  );
$$;

create function public.n5_soru_ekle(p_soru jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v public.n5_questions;
begin
  perform public.n5_soru_dogrula(p_soru);
  insert into public.n5_questions (id, soru, dogru, yanlislar, kategori, ipucu, aciklama, yanlis_aciklamalar, aktif)
  values (
    p_soru->>'id', p_soru->>'soru', p_soru->>'dogru',
    array(select jsonb_array_elements_text(p_soru->'yanlislar')),
    p_soru->>'kategori', p_soru->>'ipucu', p_soru->>'aciklama',
    array(select jsonb_array_elements_text(p_soru->'yanlisAciklamalar')),
    coalesce((p_soru->>'aktif')::boolean, true)
  )
  returning * into v;
  return public.n5_soru_json(v);
exception
  when unique_violation then
    raise exception 'Bu kimlikte bir soru zaten var.' using errcode = 'PT409';
  when check_violation or not_null_violation then
    raise exception 'Soru alanları geçersiz.' using errcode = 'PT400';
end;
$$;

-- Var olan (silinmemiş) bir soruyu günceller. Tek UPDATE: satır düzeyinde atomik.
create function public.n5_soru_guncelle(p_id text, p_soru jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v public.n5_questions;
begin
  perform public.n5_soru_dogrula(p_soru || jsonb_build_object('id', p_id));
  update public.n5_questions set
    soru = p_soru->>'soru',
    dogru = p_soru->>'dogru',
    yanlislar = array(select jsonb_array_elements_text(p_soru->'yanlislar')),
    kategori = p_soru->>'kategori',
    ipucu = p_soru->>'ipucu',
    aciklama = p_soru->>'aciklama',
    yanlis_aciklamalar = array(select jsonb_array_elements_text(p_soru->'yanlisAciklamalar')),
    aktif = coalesce((p_soru->>'aktif')::boolean, true),
    guncelleme = now()
  where id = p_id and silindi is null
  returning * into v;
  if not found then
    raise exception 'Soru bulunamadı.' using errcode = 'PT404';
  end if;
  return public.n5_soru_json(v);
exception
  when check_violation or not_null_violation then
    raise exception 'Soru alanları geçersiz.' using errcode = 'PT400';
end;
$$;

-- Soruyu siler (mezar taşı bırakır; seed yeniden çalışınca geri gelmez).
create function public.n5_soru_sil(p_id text)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
begin
  update public.n5_questions set silindi = now(), aktif = false, guncelleme = now()
   where id = p_id and silindi is null;
  if not found then
    raise exception 'Soru bulunamadı.' using errcode = 'PT404';
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

-- Toplu içe aktarma: listedeki sorular eklenir/güncellenir (silinmişse geri gelir), listede olmayanlar
-- silinir. Tek fonksiyon = tek işlem: ya hepsi uygulanır ya hiçbiri.
create function public.n5_sorulari_degistir(p_sorular jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  e jsonb;
  v_sayi integer := 0;
begin
  if jsonb_typeof(p_sorular) is distinct from 'array' or jsonb_array_length(p_sorular) > 2000 then
    raise exception 'Geçersiz dosya: soru listesi bekleniyor.' using errcode = 'PT400';
  end if;
  if (select count(distinct x->>'id') from jsonb_array_elements(p_sorular) x) <> jsonb_array_length(p_sorular) then
    raise exception 'Listede yinelenen soru kimliği var.' using errcode = 'PT400';
  end if;
  for e in select value from jsonb_array_elements(p_sorular) loop
    perform public.n5_soru_dogrula(e);
    insert into public.n5_questions (id, soru, dogru, yanlislar, kategori, ipucu, aciklama, yanlis_aciklamalar, aktif)
    values (
      e->>'id', e->>'soru', e->>'dogru', array(select jsonb_array_elements_text(e->'yanlislar')),
      e->>'kategori', e->>'ipucu', e->>'aciklama', array(select jsonb_array_elements_text(e->'yanlisAciklamalar')),
      coalesce((e->>'aktif')::boolean, true)
    )
    on conflict (id) do update set
      soru = excluded.soru, dogru = excluded.dogru, yanlislar = excluded.yanlislar, kategori = excluded.kategori,
      ipucu = excluded.ipucu, aciklama = excluded.aciklama, yanlis_aciklamalar = excluded.yanlis_aciklamalar,
      aktif = excluded.aktif, silindi = null, guncelleme = now();
    v_sayi := v_sayi + 1;
  end loop;
  update public.n5_questions set silindi = now(), aktif = false, guncelleme = now()
   where silindi is null and id not in (select x->>'id' from jsonb_array_elements(p_sorular) x);
  return jsonb_build_object('ok', true, 'count', v_sayi);
exception
  when check_violation or not_null_violation then
    raise exception 'Soru alanları geçersiz.' using errcode = 'PT400';
end;
$$;

-- Ayarları günceller. p_surum, okunan ayarların sürümüdür; arada başka bir yazma olduysa 409.
create function public.n5_ayarlari_guncelle(p_ayarlar jsonb, p_surum integer)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v public.n5_settings;
begin
  if jsonb_typeof(p_ayarlar) is distinct from 'object' or p_surum is null then
    raise exception 'Geçersiz ayarlar.' using errcode = 'PT400';
  end if;
  update public.n5_settings set
    questions_per_game = (p_ayarlar->>'questionsPerGame')::integer,
    end_on_wrong = (p_ayarlar->>'endOnWrong')::boolean,
    seconds_per_question = (p_ayarlar->>'secondsPerQuestion')::integer,
    surum = surum + 1,
    guncelleme = now()
  where id and surum = p_surum
  returning * into v;
  if not found then
    raise exception 'Ayarlar başka bir oturumda değiştirildi. Güncel ayarlar yüklendi; tekrar kaydedin.' using errcode = 'PT409';
  end if;
  return public.n5_ayarlar_json(v);
exception
  when check_violation or not_null_violation or invalid_text_representation then
    raise exception 'Geçersiz ayarlar.' using errcode = 'PT400';
end;
$$;

-- İstatistikleri sıfırlar. Kayıtlı oyun kimlikleri korunur: eski bir oyunun yeniden gönderimi yine sayılmaz.
create function public.n5_istatistik_sifirla()
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
begin
  delete from public.n5_question_stats where true;
  update public.n5_stats_totals set games = 0, finished = 0, total_correct = 0, guncelleme = now() where id;
  return jsonb_build_object('ok', true);
end;
$$;

-- ---------------------------------------------------------------------------
-- Seed ve veri aktarımı (migration / bakım betikleri)
-- ---------------------------------------------------------------------------

-- Varsayılan soruları ekler. Var olan (silinmiş, pasif ya da düzenlenmiş) sorulara dokunmaz:
-- tekrar çalıştırmak yinelenen kayıt üretmez ve yönetici değişikliklerini ezmez.
create function public.n5_soru_tohumla(p_sorular jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  e jsonb;
  v_eklenen integer := 0;
  v_sayi integer;
begin
  if jsonb_typeof(p_sorular) is distinct from 'array' then
    raise exception 'Geçersiz seed.' using errcode = 'PT400';
  end if;
  for e in select value from jsonb_array_elements(p_sorular) loop
    perform public.n5_soru_dogrula(e);
    insert into public.n5_questions (id, soru, dogru, yanlislar, kategori, ipucu, aciklama, yanlis_aciklamalar, aktif, olusturma)
    values (
      e->>'id', e->>'soru', e->>'dogru', array(select jsonb_array_elements_text(e->'yanlislar')),
      e->>'kategori', e->>'ipucu', e->>'aciklama', array(select jsonb_array_elements_text(e->'yanlisAciklamalar')),
      coalesce((e->>'aktif')::boolean, true),
      coalesce((e->>'olusturma')::timestamptz, now())
    )
    on conflict (id) do nothing;
    get diagnostics v_sayi = row_count;
    v_eklenen := v_eklenen + v_sayi;
  end loop;
  return jsonb_build_object('eklenen', v_eklenen, 'mevcut', jsonb_array_length(p_sorular) - v_eklenen);
end;
$$;

-- Eski JSON kurulumunun istatistiklerini bir kez aktarır (aynı p_aktarim_id ikinci kez uygulanmaz).
create function public.n5_istatistik_aktar(p_aktarim_id text, p_istatistik jsonb)
returns jsonb
