-- Nasodren 5 ("Kim Nefes Almak İster?") — kalıcı veri şeması.
--
-- ORTAK SUPABASE PROJESİ: Bu proje önceki dört oyunun verisini de barındırır. Beşinci oyunun TÜM
-- nesneleri (tablolar, otomatik adlı indeks/kısıt/dizi/tipler dahil) ve fonksiyonları public şemasında
-- "n5_" önekiyle oluşturulur. Başka hiçbir nesneye dokunulmaz, hiçbir şey silinmez ya da yeniden adlandırılmaz.
--
-- UYGULAMA: Supabase SQL Editor'e bu dosyanın TAMAMINI yapıştırıp çalıştırın (tek işlem: ya hepsi ya hiçbiri).
--   * Başta ön kontrol vardır: public şemasında "n5_" önekli herhangi bir nesne zaten varsa hiçbir şey
--     yapılmadan durur (çakışma ya da ikinci kez uygulama).
--   * "if not exists" / "or replace" bilerek kullanılmaz: bir ad çakışırsa sessizce başka bir nesneye
--     uygulanmak yerine hata verilir ve işlem geri alınır.
--   * Uygulanan sürüm public.n5_migrations tablosuna yazılır (ortak supabase_migrations geçmişine yazılmaz).
--
-- Erişim modeli:
--   * Tarayıcılar Supabase'e HİÇ bağlanmaz. Tek istemci Cloudflare Worker'dır ve service_role anahtarıyla
--     yalnızca aşağıdaki n5_* fonksiyonlarını (PostgREST RPC) çağırır.
--   * n5_ tablolarında RLS açıktır ve hiçbir politika yoktur: anon / authenticated rolleri bu tabloları
--     okuyamaz, yazamaz. Supabase'in public şemasına varsayılan olarak verdiği yetkiler YALNIZCA n5_
--     nesneleri için açıkça geri alınır.
--   * Fonksiyonlar SECURITY INVOKER çalışır, search_path boştur ve tüm adlar şema ile nitelenir.
--     EXECUTE yalnızca service_role'e verilir.
--   * Fonksiyonların fırlattığı 'PTxyz' hata kodları PostgREST tarafından HTTP xyz durumuna çevrilir.

begin;

-- ---------------------------------------------------------------------------
-- Ön kontrol (salt okunur): n5_ önekli hiçbir nesne olmamalı
-- ---------------------------------------------------------------------------
do $n5$
begin
  if exists (select 1 from pg_catalog.pg_class where relnamespace = 'public'::regnamespace and left(relname, 3) = 'n5_')
     or exists (select 1 from pg_catalog.pg_type where typnamespace = 'public'::regnamespace and left(typname, 3) = 'n5_')
     or exists (select 1 from pg_catalog.pg_proc where pronamespace = 'public'::regnamespace and left(proname, 3) = 'n5_') then
    raise exception 'N5: public şemasında "n5_" önekli nesne zaten var (çakışma ya da ikinci uygulama). Hiçbir değişiklik yapılmadı.';
  end if;
end
$n5$;

-- Beşinci oyunun kendi migration kaydı (ortak geçmişten bağımsız).
create table public.n5_migrations (
  surum      text primary key check (surum ~ '^[0-9]{14}$'),
  uygulandi  timestamptz not null default now()
);
alter table public.n5_migrations enable row level security;
revoke all on table public.n5_migrations from public, anon, authenticated;
grant select, insert on table public.n5_migrations to service_role;

-- ---------------------------------------------------------------------------
-- Tablolar
-- ---------------------------------------------------------------------------

create table public.n5_questions (
  id                 text primary key check (id ~ '^[A-Za-z0-9_-]{1,64}$'),
  -- Yönetici panelindeki kararlı sıra (yeni soru sona eklenir).
  sira               bigint generated by default as identity unique,
  soru               text not null check (char_length(soru) between 1 and 300),
  dogru              text not null check (char_length(dogru) between 1 and 120),
  yanlislar          text[] not null check (cardinality(yanlislar) = 3),
  kategori           text not null check (char_length(kategori) between 1 and 60),
  ipucu              text not null check (char_length(ipucu) between 1 and 300),
  aciklama           text not null check (char_length(aciklama) between 1 and 400),
  yanlis_aciklamalar text[] not null check (cardinality(yanlis_aciklamalar) = 3),
  aktif              boolean not null default true,
  olusturma          timestamptz not null default now(),
  guncelleme         timestamptz not null default now(),
  -- Silinen soru satırı kalır (mezar taşı): seed yeniden çalıştırılınca geri gelmez.
  silindi            timestamptz
);
create index n5_questions_aktif_idx on public.n5_questions (sira) where silindi is null and aktif;

-- Tek satırlık oyun ayarları. surum: iyimser eşzamanlılık (eski sürümle yazma 409 alır).
create table public.n5_settings (
  id                   boolean primary key default true check (id),
  questions_per_game   integer not null default 15 check (questions_per_game between 1 and 50),
  end_on_wrong         boolean not null default true,
  seconds_per_question integer not null default 30 check (seconds_per_question between 0 and 180),
  surum                integer not null default 1 check (surum >= 1),
  guncelleme           timestamptz not null default now()
);
insert into public.n5_settings (id) values (true) on conflict (id) do nothing;

-- Tek oyunculu oyunların toplamları (tek satır).
create table public.n5_stats_totals (
  id            boolean primary key default true check (id),
  games         bigint not null default 0 check (games >= 0),
  finished      bigint not null default 0 check (finished >= 0),
  total_correct bigint not null default 0 check (total_correct >= 0),
  guncelleme    timestamptz not null default now()
);
insert into public.n5_stats_totals (id) values (true) on conflict (id) do nothing;

-- Soru başına başarı (tek oyunculu + çok oyunculu cevaplar). Silinen sorunun istatistiği korunur.
create table public.n5_question_stats (
  question_id text primary key,
  asked       bigint not null default 0 check (asked >= 0),
  correct     bigint not null default 0 check (correct >= 0 and correct <= asked)
);

-- Kaydedilmiş oyunlar: aynı oyunun ikinci kez sayılmasını engeller (idempotency anahtarı).
create table public.n5_game_results (
  game_id  uuid primary key,
  tur      text not null check (tur in ('tek', 'canli')),
  finished boolean not null,
  answers  integer not null check (answers between 0 and 1000),
  correct  integer not null check (correct between 0 and answers),
  kayit    timestamptz not null default now()
);

-- Bir kez yapılması gereken veri aktarımları (ör. eski JSON istatistiklerinin taşınması).
create table public.n5_data_imports (
  import_id text primary key check (char_length(import_id) between 1 and 200),
  kayit     timestamptz not null default now()
);

