-- Herkese açık özet: ayarlar ve aktif soru sayısı (cevap anahtarı yok).
create function public.n5_genel_durum()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'ayarlar', (select public.n5_ayarlar_json(s) - 'surum' from public.n5_settings s where s.id),
    'aktifSoru', (select count(*) from public.n5_questions q where q.silindi is null and q.aktif)
  );
$$;

-- Oyun oturumu / oda kurmak için aktif sorular (tam veri; yalnızca Worker okur) ve ayarlar.
create function public.n5_oyun_verisi()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'questions', coalesce((
      select jsonb_agg(public.n5_soru_json(q) order by q.sira)
      from public.n5_questions q where q.silindi is null and q.aktif
    ), '[]'::jsonb),
    'settings', (select public.n5_ayarlar_json(s) - 'surum' from public.n5_settings s where s.id)
  );
$$;

-- Biten oyunun sonucunu bir kez kaydeder. p_oyun_id ikinci kez gelirse hiçbir şey değişmez.
-- tur = 'tek': oyun toplamları ve soru başarıları; tur = 'canli': yalnızca soru başarıları.
create function public.n5_oyun_kaydet(p_oyun_id uuid, p_tur text, p_cevaplar jsonb, p_bitti boolean)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_sayi integer;
  v_dogru integer;
  v_eklendi boolean;
begin
  if p_oyun_id is null or p_tur not in ('tek', 'canli') or p_bitti is null then
    raise exception 'Geçersiz oyun kaydı.' using errcode = 'PT400';
  end if;
  if jsonb_typeof(p_cevaplar) is distinct from 'array' or jsonb_array_length(p_cevaplar) > 1000 then
    raise exception 'Geçersiz cevap listesi.' using errcode = 'PT400';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_cevaplar) e
    where jsonb_typeof(e) is distinct from 'object'
       or jsonb_typeof(e->'id') is distinct from 'string'
       or jsonb_typeof(e->'correct') is distinct from 'boolean'
  ) then
    raise exception 'Geçersiz cevap listesi.' using errcode = 'PT400';
  end if;

  select count(*), count(*) filter (where (e->>'correct')::boolean)
    into v_sayi, v_dogru
    from jsonb_array_elements(p_cevaplar) e;

  insert into public.n5_game_results (game_id, tur, finished, answers, correct)
  values (p_oyun_id, p_tur, p_bitti, v_sayi, v_dogru)
  on conflict (game_id) do nothing;
  get diagnostics v_sayi = row_count;
  v_eklendi := v_sayi = 1;
  if not v_eklendi then
    return jsonb_build_object('kaydedildi', false);
  end if;

  if p_tur = 'tek' then
    update public.n5_stats_totals
       set games = games + 1,
           finished = finished + case when p_bitti then 1 else 0 end,
           total_correct = total_correct + v_dogru,
           guncelleme = now()
     where id;
  end if;

  insert into public.n5_question_stats (question_id, asked, correct)
  select e->>'id', count(*), count(*) filter (where (e->>'correct')::boolean)
    from jsonb_array_elements(p_cevaplar) e
   group by e->>'id'
  on conflict (question_id) do update
     set asked = public.n5_question_stats.asked + excluded.asked,
         correct = public.n5_question_stats.correct + excluded.correct;

  return jsonb_build_object('kaydedildi', true);
end;
$$;

