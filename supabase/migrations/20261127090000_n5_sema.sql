declare
  v_sayi integer;
begin
  if jsonb_typeof(p_istatistik) is distinct from 'object' then
    raise exception 'Geçersiz istatistik.' using errcode = 'PT400';
  end if;
  insert into public.n5_data_imports (import_id) values (p_aktarim_id) on conflict (import_id) do nothing;
  get diagnostics v_sayi = row_count;
  if v_sayi = 0 then
    return jsonb_build_object('aktarildi', false);
  end if;
  update public.n5_stats_totals set
    games = games + greatest(0, coalesce((p_istatistik->>'games')::bigint, 0)),
    finished = finished + greatest(0, coalesce((p_istatistik->>'finished')::bigint, 0)),
    total_correct = total_correct + greatest(0, coalesce((p_istatistik->>'totalCorrect')::bigint, 0)),
    guncelleme = now()
  where id;
  insert into public.n5_question_stats (question_id, asked, correct)
  select k, greatest(0, (v->>'asked')::bigint), least(greatest(0, (v->>'correct')::bigint), greatest(0, (v->>'asked')::bigint))
    from jsonb_each(coalesce(p_istatistik->'perQuestion', '{}'::jsonb)) as t(k, v)
  on conflict (question_id) do update
     set asked = public.n5_question_stats.asked + excluded.asked,
         correct = public.n5_question_stats.correct + excluded.correct;
  return jsonb_build_object('aktarildi', true);
end;
$$;

