-- Soru satırını uygulamanın JSON biçimine çevirir (seed ile aynı alan adları).
create function public.n5_soru_json(q public.n5_questions)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'id', q.id,
    'soru', q.soru,
    'dogru', q.dogru,
    'yanlislar', to_jsonb(q.yanlislar),
    'kategori', q.kategori,
    'ipucu', q.ipucu,
    'aciklama', q.aciklama,
    'yanlisAciklamalar', to_jsonb(q.yanlis_aciklamalar),
    'aktif', q.aktif,
    'olusturma', to_char(q.olusturma at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
$$;

create function public.n5_ayarlar_json(s public.n5_settings)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'questionsPerGame', s.questions_per_game,
    'endOnWrong', s.end_on_wrong,
    'secondsPerQuestion', s.seconds_per_question,
    'surum', s.surum
  );
$$;

-- Gelen soru JSON'unu doğrular (Worker da doğrular; bu son savunma hattıdır).
create function public.n5_soru_dogrula(p jsonb)
returns void
language plpgsql
immutable
security invoker
set search_path = ''
as $$
begin
  if jsonb_typeof(p) is distinct from 'object' then
    raise exception 'Geçersiz soru.' using errcode = 'PT400';
  end if;
  if jsonb_typeof(p->'yanlislar') is distinct from 'array' or jsonb_array_length(p->'yanlislar') <> 3
     or jsonb_typeof(p->'yanlisAciklamalar') is distinct from 'array' or jsonb_array_length(p->'yanlisAciklamalar') <> 3 then
    raise exception 'Her soruda üç yanlış şık ve üç açıklama olmalıdır.' using errcode = 'PT400';
  end if;
  if coalesce(p->>'id', '') !~ '^[A-Za-z0-9_-]{1,64}$' then
    raise exception 'Geçersiz soru kimliği.' using errcode = 'PT400';
  end if;
end;
$$;

