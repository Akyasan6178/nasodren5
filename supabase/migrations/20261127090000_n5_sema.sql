alter table public.n5_questions      enable row level security;
alter table public.n5_settings       enable row level security;
alter table public.n5_stats_totals   enable row level security;
alter table public.n5_question_stats enable row level security;
alter table public.n5_game_results   enable row level security;
alter table public.n5_data_imports   enable row level security;

