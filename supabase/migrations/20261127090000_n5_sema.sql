  public.n5_game_results, public.n5_data_imports from public, anon, authenticated;
grant select, insert, update, delete on table public.n5_questions, public.n5_settings, public.n5_stats_totals,
  public.n5_question_stats, public.n5_game_results, public.n5_data_imports to service_role;
revoke all on sequence public.n5_questions_sira_seq from public, anon, authenticated;
grant usage, select on sequence public.n5_questions_sira_seq to service_role;

